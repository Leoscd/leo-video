'use strict';
const fs=require('node:fs/promises');
const path=require('node:path');
const os=require('node:os');
const assert=require('node:assert/strict');
const {probe,run,exportVideo}=require('../core/media');
const {transcribe}=require('../core/captions');
(async()=>{
  const dir=path.resolve('test-output');await fs.mkdir(dir,{recursive:true});
  const id=Date.now(),src=path.join(dir,`persona-${id}.mp4`);
  await run('ffmpeg',['-v','error','-n','-loop','1','-i',path.join(dir,'persona-prueba.png'),'-t','0.8','-r','24','-c:v','libx264','-pix_fmt','yuv420p',src]);
  const info=await probe(src);
  const p={version:2,format:'original',fps:24,clips:[{start:0,end:.75}],effects:[{id:'persona',type:'text',start:.08,end:.7,text:'DETRÁS',layer:'behind',animation:'none',x:.5,y:.28,size:.23,color:'#F4C466'}]};
  const out=path.join(dir,`mascara-${id}.mp4`);
  await exportVideo(info,p,out,{});
  await fs.copyFile(out,path.join(dir,'resultado-mascara.mp4'));
  await run('ffmpeg',['-v','error','-y','-ss','0.4','-i',out,'-frames:v','1',path.join(dir,'resultado-mascara.png')]);
  const front=path.join(dir,`frente-${id}.mp4`);p.effects[0].layer='front';await exportVideo(info,p,front,{});
  await run('ffmpeg',['-v','error','-y','-ss','0.4','-i',front,'-frames:v','1',path.join(dir,'resultado-frente.png')]);
  assert.notDeepEqual(await fs.readFile(path.join(dir,'resultado-mascara.png')),await fs.readFile(path.join(dir,'resultado-frente.png')));
  console.log('Máscara humana y composición delante/detrás: OK.');
  const speech=path.join(os.homedir(),'.cache/hyperframes/whisper/whisper.cpp/samples/jfk.wav');
  const sample=path.join(dir,`voz-${id}.mp4`);
  await run('ffmpeg',['-v','error','-n','-f','lavfi','-i','color=c=gray:size=320x180:rate=30:duration=6','-i',speech,'-t','6','-c:v','libx264','-c:a','aac','-shortest',sample]);
  const spoken=await probe(sample),job={};const cues=await transcribe(spoken,dir,job,run,'en');
  assert.ok(cues.length>3,JSON.stringify(cues));assert.ok(cues.every(c=>c.start>=0&&c.end>c.start&&c.end<=spoken.duration));
  await fs.writeFile(path.join(dir,'transcripcion-verificada.json'),JSON.stringify(cues,null,2));
  console.log(`Whisper local: OK, ${cues.length} palabras. Texto: ${cues.map(c=>c.text).join(' ')}`);
})().catch(e=>{console.error(e);process.exitCode=1;});
